#include <cstdint>   
#include <iostream>  

int main() {
    std::uint32_t orange = 0xFF8800;  

    // Дістаємо кожен байт: зсуваємо потрібний байт на місце молодшого
    // і маскою 0xFF залишаємо лише його 8 бітів
    int r = (orange >> 16) & 0xFF;  // червоний: старший байт, 0xFF = 255
    int g = (orange >> 8) & 0xFF;   // зелений: середній байт, 0x88 = 136
    int b = orange & 0xFF;          // синій: молодший байт, 0x00 = 0
    std::cout << r << ' ' << g << ' ' << b << '\n';  // друкує: 255 136 0

    // Пакуємо в RGB565 (16 біт): 5 біт червоного, 6 зеленого, 5 синього
    // r >> 3 лишає 5 старших бітів (255 -> 31), зсув << 11 ставить їх на місце
    // g >> 2 лишає 6 старших бітів (136 -> 34), зсув << 5 ставить їх у середину
    // b >> 3 лишає 5 старших бітів (0 -> 0), вони йдуть у молодші біти
    // | склеює три частини в одне 16-бітне число
    std::uint16_t rgb565 = (std::uint16_t)(((r >> 3) << 11) | ((g >> 2) << 5) | (b >> 3));

    // std::hex перемикає друк чисел на шістнадцяткову систему
    std::cout << std::hex << rgb565 << '\n';  // очікується fc40
}