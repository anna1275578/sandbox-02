#include <cstdint>   
#include <iostream>  

// Повертає true, якщо в байті b непарна кількість одиниць
bool parity(std::uint8_t b) {
    int count = 0;           
    while (b != 0) {         
        count += b & 1;      // беремо молодший біт (0 або 1) і додаємо до лічильника
        b >>= 1;             // зсуваємо байт праворуч: наступний біт стає молодшим
    }
    return (count & 1) == 1; // молодший біт лічильника = 1 -> кількість непарна
}

int main() {
    // перевіряємо три байти, друкуємо результати через пробіл
    std::cout << parity(0xA3) << ' ' << parity(0x07) << ' ' << parity(0xFF) << '\n';
}